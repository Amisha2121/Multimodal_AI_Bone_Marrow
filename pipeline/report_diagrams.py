def generate_all_diagrams(
    case_id: str,
    summary: Dict[str, Any],
    cells: List[Dict[str, Any]],
    top4_ids: List[str]
) -> Dict[str, str]:
    """Generate and return paths to diagrams D1 through D4."""
    sens = blast_sensitivity_range(cells, summary.get("total_cells", 49))
    d1 = generate_d1_pipeline_provenance(case_id, summary, top4_ids)
    d2 = generate_d2_blast_ruler(case_id, summary.get("blast_fraction", 0.102), summary.get("total_cells", 49), sens)
    d3 = generate_d3_confusion_neighbours(case_id, cells)
    d4 = generate_d4_evidence_chain(case_id)

    return {
        "d1": str(d1),
        "d2": str(d2),
        "d3": str(d3),
        "d4": str(d4),
    }

