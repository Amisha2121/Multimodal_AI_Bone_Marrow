def generate_d2_blast_ruler(
    case_id: str,
    blast_fraction: float,
    total_cells: int,
    sensitivity_range: Dict[str, Any],
    force_regen: bool = False
) -> Path:
    """
    D2: Blast Ruler Diagram
    0-100% horizontal axis with:
      - Observed blast % marker
      - Wilson 95% CI band
      - Sensitivity range band (heuristic)
      - Literature reference tick marks: 5% (MDS threshold), 10% (CML accelerated), 20% (Acute Leukemia)
    """
    out_path = get_derived_dir(case_id) / "d2_blast_ruler.svg"
    if out_path.exists() and not force_regen:
        return out_path

    blast_k = int(round(blast_fraction * total_cells))
    ci = wilson_interval(blast_k, total_cells, z=1.96) or (0.04, 0.22)
    ci_low_pct = ci[0] * 100
    ci_high_pct = ci[1] * 100

    obs_pct = blast_fraction * 100
    sens_low = sensitivity_range.get("lower_pct", 2.0)
    sens_high = sensitivity_range.get("upper_pct", 36.7)

    # Coordinate mapping: axis width = 750px (from x=80 to x=830) -> 1% = 7.5px
    def p2x(p):
        return 80 + min(100.0, max(0.0, p)) * 7.5

    x_obs = p2x(obs_pct)
    x_ci_low = p2x(ci_low_pct)
    x_ci_high = p2x(ci_high_pct)
    x_sens_low = p2x(sens_low)
    x_sens_high = p2x(sens_high)

    spans_ref = (ci_low_pct <= 5.0 <= ci_high_pct) or (ci_low_pct <= 10.0 <= ci_high_pct) or (ci_low_pct <= 20.0 <= ci_high_pct)
    caution_note = "This sample cannot discriminate between reference points (CI spans 5%–20%)" if spans_ref else "Observed proportions placed in reference context"

    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 920 220" width="100%" height="220" style="font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;">
  <rect width="100%" height="100%" fill="#ffffff" rx="8"/>

  <text x="80" y="28" font-size="13" font-weight="700" fill="#1e293b">D2: Blast Ruler &amp; Literature Thresholds ({case_id})</text>
  <text x="80" y="46" font-size="10.5" fill="#64748b">Comparison against diagnostic boundary points cited in literature (LIT-05)</text>

  <!-- Sensitivity range band (light purple) -->
  <rect x="{x_sens_low}" y="70" width="{max(4, x_sens_high - x_sens_low)}" height="38" fill="#ede9fe" rx="4" opacity="0.8"/>
  <text x="{x_sens_high + 6}" y="85" font-size="9" fill="#7c3aed" font-weight="600">Sensitivity: {sens_low}%–{sens_high}%</text>

  <!-- Wilson 95% CI band (light blue) -->
  <rect x="{x_ci_low}" y="80" width="{max(4, x_ci_high - x_ci_low)}" height="18" fill="#bfdbfe" rx="3" opacity="0.9"/>
  <text x="{x_ci_low}" y="112" font-size="9" fill="#2563eb" font-weight="600">Wilson 95% CI ({ci_low_pct:.1f}%–{ci_high_pct:.1f}%)</text>

  <!-- Main Axis Line -->
  <line x1="80" y1="89" x2="830" y2="89" stroke="#94a3b8" stroke-width="2"/>

  <!-- Ticks for 0%, 5%, 10%, 20%, 50%, 100% -->
  <line x1="{p2x(0)}" y1="83" x2="{p2x(0)}" y2="95" stroke="#64748b" stroke-width="2"/>
  <text x="{p2x(0)}" y="132" text-anchor="middle" font-size="10" fill="#64748b">0%</text>

  <!-- Reference Threshold 5%: MDS -->
  <line x1="{p2x(5)}" y1="75" x2="{p2x(5)}" y2="103" stroke="#d97706" stroke-width="2" stroke-dasharray="3,3"/>
  <text x="{p2x(5)}" y="62" text-anchor="middle" font-size="9" font-weight="700" fill="#d97706">5% (MDS)</text>

  <!-- Reference Threshold 10%: Accelerated -->
  <line x1="{p2x(10)}" y1="75" x2="{p2x(10)}" y2="103" stroke="#ea580c" stroke-width="2" stroke-dasharray="3,3"/>
  <text x="{p2x(10)}" y="146" text-anchor="middle" font-size="9" font-weight="700" fill="#ea580c">10% (CML-AP)</text>

  <!-- Reference Threshold 20%: Acute Leukemia -->
  <line x1="{p2x(20)}" y1="75" x2="{p2x(20)}" y2="103" stroke="#dc2626" stroke-width="2.5" stroke-dasharray="3,3"/>
  <text x="{p2x(20)}" y="62" text-anchor="middle" font-size="9" font-weight="700" fill="#dc2626">20% (Acute)</text>

  <line x1="{p2x(50)}" y1="83" x2="{p2x(50)}" y2="95" stroke="#64748b" stroke-width="2"/>
  <text x="{p2x(50)}" y="132" text-anchor="middle" font-size="10" fill="#64748b">50%</text>

  <line x1="{p2x(100)}" y1="83" x2="{p2x(100)}" y2="95" stroke="#64748b" stroke-width="2"/>
  <text x="{p2x(100)}" y="132" text-anchor="middle" font-size="10" fill="#64748b">100%</text>

  <!-- Observed Blast Marker -->
  <circle cx="{x_obs}" cy="89" r="6.5" fill="#ef4444" stroke="#ffffff" stroke-width="2"/>
  <text x="{x_obs}" y="74" text-anchor="middle" font-size="11" font-weight="800" fill="#b91c1c">Observed: {obs_pct:.1f}%</text>

  <!-- Subtext caution -->
  <text x="80" y="190" font-size="10" fill="#b45309" font-style="italic">
    Note: {caution_note}. Diagnostic thresholds are provided as context only.
  </text>
</svg>'''

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(svg)
    return out_path


